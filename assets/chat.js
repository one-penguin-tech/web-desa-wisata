/* Floating chat assistant.
   Mode 1 (default): answers locally from the site's own data (window.FORKOM_DATA, generated by build.py).
   Mode 2: set window.FORKOM_CHAT_ENDPOINT = 'https://your-server/chat' before this script loads.
           The endpoint receives POST {messages:[{role,content}...]} and must reply {reply:"text"}.
           Keep any API key on that server; never put it in this file. Replies are rendered as plain text.
   If nothing matches, the bot offers to hand the question to the admin on WhatsApp. */
(function(){
  var D=window.FORKOM_DATA;if(!D)return;
  var dock=document.querySelector('.float-dock');if(!dock)return;
  var KEY='forkom-chat',ENDPOINT=window.FORKOM_CHAT_ENDPOINT||'';
  var WA=D.wa;
  var waLink=function(t){return WA+encodeURIComponent(t)};
  var norm=function(s){return s.toLowerCase().replace(/[^a-z0-9 ]+/g,' ').replace(/\s+/g,' ').trim()};
  var esc=function(s){var d=document.createElement('div');d.textContent=s;return d.innerHTML};

  var btn=document.createElement('button');
  btn.type='button';btn.className='fab fab-chat';btn.setAttribute('aria-expanded','false');btn.setAttribute('aria-controls','chat-panel');
  btn.innerHTML='<i class="ph ph-chat-circle-text" aria-hidden="true"></i><span>Tanya Asisten</span>';
  dock.insertBefore(btn,dock.firstChild);

  var panel=document.createElement('div');
  panel.className='chat';panel.id='chat-panel';panel.setAttribute('role','dialog');panel.setAttribute('aria-label','Asisten Forkom Deswita');
  panel.innerHTML='<div class="chat-head"><div><b>Asisten Forkom</b><small>Jawaban otomatis dari data situs ini</small></div><button type="button" class="chat-close" aria-label="Tutup chat"><i class="ph ph-x" aria-hidden="true"></i></button></div>'+
    '<div class="chat-log" role="log" aria-live="polite"></div>'+
    '<div class="chat-sugg"></div>'+
    '<form class="chat-form"><label for="chat-in" class="sr" style="position:absolute;left:-9999px">Pertanyaan Anda</label><input id="chat-in" autocomplete="off" maxlength="300" placeholder="Tulis pertanyaan"><button class="btn btn-dark" type="submit" aria-label="Kirim"><i class="ph ph-paper-plane-right" aria-hidden="true"></i></button></form>';
  document.body.appendChild(panel);
  var log=panel.querySelector('.chat-log'),sugg=panel.querySelector('.chat-sugg'),form=panel.querySelector('form'),input=panel.querySelector('input');

  var history=[];
  var save=function(){try{sessionStorage.setItem(KEY,JSON.stringify(history.slice(-30)))}catch(e){}};
  var add=function(role,content,html,persist){
    var m=document.createElement('div');m.className='msg '+role;
    if(html)m.innerHTML=content;else m.textContent=content;
    log.appendChild(m);log.scrollTop=log.scrollHeight;
    if(persist!==false){history.push({role:role==='user'?'user':'assistant',content:content,html:!!html});save()}
    return m;
  };

  // ---- local knowledge ----
  var money=function(p){return 'Rp '+p+' / orang'};
  var pkgLine=function(p){return '<b>'+esc(p.name)+'</b> ('+esc(p.desa)+', '+esc(p.dur)+'): '+money(p.price)};
  var orderLink=function(name){return '<a href="'+waLink('Halo Admin Forkom Deswita, saya tertarik pesan '+name+' di Kabupaten Bogor. Mohon informasi selanjutnya.')+'" target="_blank" rel="noopener">Pesan lewat WhatsApp</a>'};
  var find=function(list,q){return list.filter(function(x){return q.indexOf(norm(x.name))>-1||q.indexOf(norm(x.short||''))>-1&&x.short})};

  var rules=[
    {k:['halo','hai','selamat','sampurasun','hi '],a:function(){return 'Sampurasun! Saya bisa membantu soal desa wisata, paket, event, dan cara bergabung. Ada yang ingin ditanyakan?'}},
    {k:['gabung','daftar forum','anggota','join'],a:function(){return 'Pokdarwis, pengelola homestay, dan pegiat desa bisa bergabung. <a href="'+waLink('Halo Admin Forkom Deswita, saya ingin bergabung dengan forum.')+'" target="_blank" rel="noopener">Hubungi admin lewat WhatsApp</a>.'}},
    {k:['kontak','alamat','sekretariat','telepon','email','hubungi'],a:function(){return '<b>Sekretariat</b><br>'+esc(D.contact.address)+'<br>Telepon: '+esc(D.contact.phone)+'<br>Email: '+esc(D.contact.email)}},
    {k:['harga','biaya','tarif','paket','pesan','booking','book','menginap','live in','trekking','camping','glamping','agro'],a:function(q){
      var hit=D.packages.filter(function(p){var t=norm(p.name+' '+p.desa+' '+p.id);return q.split(' ').some(function(w){return w.length>3&&t.indexOf(w)>-1&&['paket','harga','biaya','pesan','desa','wisata'].indexOf(w)<0})});
      if(hit.length===1){var p=hit[0];return pkgLine(p)+'.<br>'+esc(p.desc)+'<br>'+orderLink(p.name)}
      return 'Paket yang tersedia:<br>'+D.packages.map(pkgLine).join('<br>')+'<br><a href="paket-wisata.html">Lihat detail paket</a>';
    }},
    {k:['event','festival','acara','jadwal','agenda','seren taun','upacara'],a:function(){return 'Agenda 2026:<br>'+D.events.map(function(e){return '<b>'+esc(e.name)+'</b>, '+esc(e.d)+' '+esc(e.m)+', '+esc(e.where)}).join('<br>')+'<br>Tanggal edisi berikutnya bisa ditanyakan ke admin. <a href="event.html">Semua event</a>'}},
    {k:['webinar','pelatihan','diskusi','chse','komunitas','aspirasi'],a:function(){return 'Webinar dan pelatihan ada di <a href="komunitas.html">Ruang Komunitas</a>, termasuk pemasaran digital, standar homestay CHSE, dan diskusi pengelolaan lahan desa.'}},
    {k:['budaya','adat','angklung','silat','sunda','liwet','anyaman'],a:function(){return 'Budaya Sunda hidup di desa-desa kami: Seren Taun, angklung, pencak silat, nasi liwet, dan anyaman bambu. Baca di <a href="budaya.html">halaman Budaya</a>, atau rasakan lewat paket Live In Malasari.'}},
    {k:['visi','misi','profil','forkom','siapa'],a:function(){return 'Forkom Deswita adalah forum pengelola desa wisata, Pokdarwis, masyarakat adat, dan pemerintah Kabupaten Bogor. Lihat <a href="profil.html">profil lengkap</a>.'}},
    {k:['desa','kecamatan','lokasi','dimana','di mana','direktori'],a:function(q){
      var v=D.villages.filter(function(x){return q.indexOf(norm(x.name))>-1});
      if(v.length)return v.map(function(x){return '<b>Desa Wisata '+esc(x.name)+'</b> ada di Kecamatan '+esc(x.kec)}).join('<br>');
      var k=D.kecamatan.filter(function(x){return q.indexOf(norm(x))>-1});
      if(k.length){return k.map(function(kk){var n=D.villages.filter(function(x){return x.kec===kk}).map(function(x){return x.name});return 'Kecamatan '+esc(kk)+': '+esc(n.join(', '))}).join('<br>')}
      return 'Ada '+D.villages.length+' desa wisata di direktori. Sebut nama desa atau kecamatan, atau buka <a href="desa-wisata.html">direktori desa wisata</a>.';
    }}
  ];
  var local=function(text){
    var q=' '+norm(text)+' ';
    // direct village or kecamatan mention wins
    var v=D.villages.filter(function(x){return q.indexOf(' '+norm(x.name)+' ')>-1});
    if(v.length&&!/harga|paket|pesan/.test(q))return v.map(function(x){return '<b>Desa Wisata '+esc(x.name)+'</b> ada di Kecamatan '+esc(x.kec)+'. Untuk info kunjungan, <a href="'+waLink('Halo Admin Forkom Deswita, saya ingin info kunjungan ke Desa Wisata '+x.name+'.')+'" target="_blank" rel="noopener">tanya admin</a>.'}).join('<br>');
    for(var i=0;i<rules.length;i++){
      if(rules[i].k.some(function(w){return q.indexOf(' '+w.trim()+' ')>-1||(w.length>4&&q.indexOf(w)>-1)}))return rules[i].a(norm(text));
    }
    return null;
  };
  var fallback=function(text){return 'Maaf, saya belum punya jawaban untuk itu. <a href="'+waLink('Halo Admin Forkom Deswita, saya ingin bertanya: '+text)+'" target="_blank" rel="noopener">Teruskan pertanyaan ke admin lewat WhatsApp</a>.'};

  var ask=function(text){
    add('user',text);
    var wait=add('bot','Mengetik...',false,false);wait.classList.add('typing');
    var done=function(content,html){wait.remove();add('bot',content,html)};
    if(ENDPOINT){
      var ctl=new AbortController(),to=setTimeout(function(){ctl.abort()},15000);
      fetch(ENDPOINT,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({messages:history.map(function(h){return {role:h.role,content:h.content}})}),signal:ctl.signal})
        .then(function(r){if(!r.ok)throw new Error(r.status);return r.json()})
        .then(function(j){clearTimeout(to);if(!j||typeof j.reply!=='string')throw new Error('bad');done(j.reply,false)})
        .catch(function(){var l=local(text);done(l||fallback(text),true)});
    }else{
      setTimeout(function(){var l=local(text);done(l||fallback(text),true)},450);
    }
  };

  ['Harga paket wisata','Jadwal event','Desa di Cisarua','Cara bergabung'].forEach(function(t){
    var b=document.createElement('button');b.type='button';b.textContent=t;b.addEventListener('click',function(){ask(t)});sugg.appendChild(b);
  });
  form.addEventListener('submit',function(e){e.preventDefault();var t=input.value.trim();if(!t)return;input.value='';ask(t)});

  var open=function(){panel.classList.add('open');btn.setAttribute('aria-expanded','true');input.focus()};
  var close=function(){panel.classList.remove('open');btn.setAttribute('aria-expanded','false');btn.focus()};
  btn.addEventListener('click',function(){panel.classList.contains('open')?close():open()});
  panel.querySelector('.chat-close').addEventListener('click',close);
  panel.addEventListener('keydown',function(e){if(e.key==='Escape')close()});

  // restore session or greet
  try{history=JSON.parse(sessionStorage.getItem(KEY))||[]}catch(e){history=[]}
  if(history.length){var h=history;history=[];h.forEach(function(m){add(m.role==='user'?'user':'bot',m.content,m.html,false);history.push(m)})}
  else add('bot','Sampurasun! Saya asisten Forkom Deswita. Tanyakan soal desa wisata, paket, event, atau cara bergabung.',false);
})();
